function getExtensionApi() {
  const chromiumApi = globalThis['ch' + 'rome']
  return globalThis.browser?.i18n ? globalThis.browser : chromiumApi
}

export function normalizeLocale(locale = '') {
  const value = String(locale).replace('-', '_')
  const lower = value.toLowerCase()

  if (lower.startsWith('zh_tw') || lower.startsWith('zh_hk') || lower.startsWith('zh_mo') || lower.includes('hant')) {
    return 'zh_TW'
  }

  if (lower.startsWith('zh')) {
    return 'zh_CN'
  }

  return 'en'
}

export function getCurrentLocale() {
  const extensionLocale = getExtensionApi()?.i18n?.getUILanguage?.()
  return normalizeLocale(extensionLocale || globalThis.navigator?.language || DEFAULT_LOCALE)
}

function interpolate(message, params = {}) {
  return message.replace(/\{(\w+)\}/g, (match, key) => (
    Object.prototype.hasOwnProperty.call(params, key) ? String(params[key]) : match
  ))
}

export function createTranslator(locale = getCurrentLocale()) {
  const normalizedLocale = normalizeLocale(locale)

  return function translate(key, params = {}) {
    const message = LOCALE_MESSAGES[normalizedLocale]?.[key]
      || LOCALE_MESSAGES[DEFAULT_LOCALE][key]
      || key

    return interpolate(message, params)
  }
}

export const t = createTranslator()

export function colorLabel(colorOrId, translate = t) {
  const colorId = typeof colorOrId === 'string' ? colorOrId : colorOrId?.id
  const fallback = typeof colorOrId === 'string' ? colorOrId : colorOrId?.label || colorId
  const translated = translate(`color.${colorId}`)

  return translated === `color.${colorId}` ? fallback : translated
}

export function createRuleDisplayNameForLocale(site, keyword = '', translate = t) {
  if (!site) return translate('common.untitledRule')

  const trimmedKeyword = String(keyword || '').trim()
  return trimmedKeyword
    ? `${site} · ${trimmedKeyword}`
    : `${site} · ${translate('common.wholeSite')}`
}
